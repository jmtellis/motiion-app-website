// Run with PGLITE_MODULE pointing at an installed @electric-sql/pglite module.
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema auth to authenticated;
create table public.talent_lists(id uuid primary key, owner_id uuid, name text);
create table public.profiles(user_id uuid primary key, display_name text, first_name text, last_name text, industry_avatar_url text, headshot_urls jsonb);
insert into public.profiles values ('00000000-0000-0000-0000-000000000002','Roster Owner',null,null,'https://example.com/avatar.png','[]');
create table public.professional_profiles(id uuid primary key, user_id uuid);
create table public.talent_list_members(list_id uuid, profile_id uuid, added_at timestamptz default now());
grant select on public.talent_lists to authenticated;
insert into public.talent_lists values ('00000000-0000-0000-0000-000000000001','00000000-0000-0000-0000-000000000002','Demo cast');
insert into public.professional_profiles values ('00000000-0000-0000-0000-000000000003','00000000-0000-0000-0000-000000000005');
insert into public.talent_list_members(list_id,profile_id) values ('00000000-0000-0000-0000-000000000001','00000000-0000-0000-0000-000000000003');
`);
await db.exec(await readFile(new URL('../../migrations/20261031163701_roster_public_links.sql', import.meta.url), 'utf8'));
await db.exec(await readFile(new URL('../../migrations/20261031164426_roster_public_profile_ids.sql', import.meta.url), 'utf8'));
await db.exec(await readFile(new URL('../../migrations/20261031170954_roster_public_sharer.sql', import.meta.url), 'utf8'));
await db.exec(await readFile(new URL('../../migrations/20261031200049_roster_public_link_duration.sql', import.meta.url), 'utf8'));
await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000002',false);`);
const { rows: [link] } = await db.query(`insert into public.talent_list_public_links(list_id,expires_at) values ('00000000-0000-0000-0000-000000000001', now()+interval '1 day') returning *`);
await db.exec(`select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000004',false);`);
assert.equal((await db.query('select * from public.talent_list_public_links')).rows.length,0);
await assert.rejects(db.exec(`insert into public.talent_list_public_links(list_id) values ('00000000-0000-0000-0000-000000000001')`));
await db.exec('set role anon');
await assert.rejects(db.query('select * from public.talent_list_public_links'));
const read = async token => (await db.query('select public.read_public_roster($1) as roster',[token])).rows[0].roster;
assert.equal((await read(link.token)).name,'Demo cast');
assert.deepEqual((await read(link.token)).sharedBy,{name:'Roster Owner',avatarUrl:'https://example.com/avatar.png'});
assert.deepEqual((await read(link.token)).profileIds,['00000000-0000-0000-0000-000000000005']);
assert.equal(await read('00000000-0000-0000-0000-000000000099'), null);
await db.exec('reset role');
await db.query("update public.talent_list_public_links set expires_at = now()-interval '1 second' where id=$1",[link.id]);
await db.exec('set role anon');
assert.equal(await read(link.token),null);
await db.exec('reset role');
await db.query('update public.talent_list_public_links set expires_at=null where id=$1',[link.id]);
await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000002',false);`);
await db.query('delete from public.talent_list_public_links where id=$1',[link.id]);
await db.exec('set role anon');
assert.equal(await read(link.token),null);
console.log('PASS: owner creation, non-owner isolation, token access, expiry, and revocation');
await db.close();
